function parseSemver(v: string) {
  const m = v.match(/^(\d+)\.(\d+)\.(\d+)(?:-(.+))?$/);
  if (!m) return null;
  return {major: +m[1], minor: +m[2], patch: +m[3], pre: m[4] ?? null};
}

function semverDesc(a: string, b: string): number {
  const va = parseSemver(a);
  const vb = parseSemver(b);
  if (!va || !vb) return b.localeCompare(a);
  if (va.major !== vb.major) return vb.major - va.major;
  if (va.minor !== vb.minor) return vb.minor - va.minor;
  if (va.patch !== vb.patch) return vb.patch - va.patch;
  if (!va.pre && vb.pre) return -1;
  if (va.pre && !vb.pre) return 1;
  if (va.pre && vb.pre) {
    const am = va.pre.match(/^(\D*)(\d+)$/);
    const bm = vb.pre.match(/^(\D*)(\d+)$/);
    if (am && bm && am[1] === bm[1]) return +bm[2] - +am[2];
    return vb.pre.localeCompare(va.pre);
  }
  return 0;
}

function versionOf(item: unknown): string {
  return String((item as {id?: string}).id ?? '').split('/').pop() ?? '';
}

// Releases read newest-first. Without this the autogenerated sidebar follows
// sidebar_position, which counts up as versions are added.
async function releasesDescendingSidebarItemsGenerator({
  defaultSidebarItemsGenerator,
  ...args
}: any) {
  const items = await defaultSidebarItemsGenerator(args);
  if (args.item.dirName === 'Releases') {
    return [...items].sort((a, b) => semverDesc(versionOf(a), versionOf(b)));
  }
  return items;
}

const GAME_SERVERS_DIR = path.join(__dirname, 'GameServers');

// Each server's docs are synced from its own repo into GameServers/<Server>, where
// the Docker page is the one people come for. That page becomes the server's landing
// page, served from /GameServers/<Server> instead of /GameServers/<Server>/Docker; a
// server with no Docker page but only one doc gets the same treatment for that doc.
function gameServerLandingDoc(server: string): string | null {
  const dir = path.join(GAME_SERVERS_DIR, server);
  if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) return null;

  const docs = fs.readdirSync(dir).filter((file) => /\.mdx?$/i.test(file));
  const docker = docs.find((file) => /^docker\.mdx?$/i.test(file));

  return docker ?? (docs.length === 1 ? docs[0] : null);
}

function gameServerLandingDocId(server: string): string | null {
  const landing = gameServerLandingDoc(server);
  return landing ? `${server}/${landing.replace(/\.mdx?$/i, '')}` : null;
}

// Collapses each server's category onto its landing page: a server with just the one
// doc becomes a single link, and one with more keeps the rest as children of a
// category that opens the landing page. Servers sort by display name, not folder name.
async function gameServersSidebarItemsGenerator({
  defaultSidebarItemsGenerator,
  ...args
}: any) {
  const items: any[] = await defaultSidebarItemsGenerator(args);

  const servers = items
    .filter((item) => item.type === 'category')
    .map((category) => {
      const firstDoc = category.items.find((item: any) => item.type === 'doc');
      if (!firstDoc) return category;

      const server = String(firstDoc.id).split('/')[0];
      const landingId = gameServerLandingDocId(server);

      if (!landingId) {
        return {...category, link: {type: 'generated-index', slug: `/${server}`}};
      }

      const rest = category.items.filter((item: any) => item.id !== landingId);

      return rest.length === 0
        ? {type: 'doc', id: landingId, label: category.label}
        : {...category, link: {type: 'doc', id: landingId}, items: rest};
    })
    .sort((a, b) => a.label.localeCompare(b.label));

  return [...items.filter((item) => item.type !== 'category'), ...servers];
}

function joinUrl(...parts: string[]): string {
  const joined = parts
    .map((part) => part.replace(/^\/+|\/+$/g, ''))
    .filter(Boolean)
    .join('/');
  return `/${joined}`;
}

// GitHub Pages serves static files only, so a real 302 is off the table: the
// closest equivalent is a route pinned at build time to the newest release,
// which redirects on the client and is kept out of the index so it never gets
// canonicalized onto the version it happens to point at today.
function latestReleaseRedirect(options: {
  id: string;
  releasesDir: string;
  routeBasePath: string;
}) {
  return function latestReleaseRedirectPlugin(
    context: LoadContext,
  ): Plugin<{version: string; to: string} | null> {
    return {
      name: `latest-release-redirect-${options.id}`,

      async loadContent() {
        const dir = path.join(context.siteDir, options.releasesDir);
        const [latest] = fs
          .readdirSync(dir)
          .filter((file) => /\.mdx?$/i.test(file))
          .map((file) => file.replace(/\.mdx?$/i, ''))
          .sort(semverDesc);

        return latest
          ? {
              version: latest,
              to: joinUrl(context.baseUrl, options.routeBasePath, 'Releases', latest),
            }
          : null;
      },

      async contentLoaded({content, actions}) {
        if (!content) {
          return;
        }

        const latest = await actions.createData(
          'latest-release.json',
          JSON.stringify(content),
        );

        actions.addRoute({
          path: joinUrl(
            context.baseUrl,
            options.routeBasePath,
            'Releases',
            'Latest',
          ),
          exact: true,
          component: '@site/src/components/LatestReleaseRedirect',
          modules: {latest},
        });
      },
    };
  };
}

